"""Tests for stable JSON and safely escaped self-contained HTML reports."""

from __future__ import annotations

from html import escape
from pathlib import Path

import pytest

from scripts.generate_demo_dataset import generate_demo_zip
from vision_doctor.config import Settings
from vision_doctor.models import (
    Diagnosis,
    PriorityFinding,
    RecommendedAction,
    Severity,
)
from vision_doctor.pipeline import run_pipeline
from vision_doctor.reports import (
    load_json_report,
    render_html_report,
    render_json_report,
    write_html_report,
    write_json_report,
)


def _report(tmp_path: Path, *, run_doctor: bool = False):
    archive = generate_demo_zip(tmp_path / "demo.zip")
    return run_pipeline(
        archive,
        settings=Settings(_env_file=None),
        temp_root=tmp_path,
        run_doctor=run_doctor,
    )


def test_json_report_round_trips_complete_audit_in_utf8(tmp_path: Path) -> None:
    report = _report(tmp_path)
    report = report.model_copy(
        update={
            "manifest": report.manifest.model_copy(
                update={"dataset_name": "视觉数据集"}
            )
        }
    )
    destination = tmp_path / "audit.json"

    assert render_json_report(report) == render_json_report(report)
    assert write_json_report(report, destination) == destination
    assert b"\xe8\xa7\x86\xe8\xa7\x89" in destination.read_bytes()

    restored = load_json_report(destination)
    assert restored == report
    assert restored.schema_version == "1.0.0"
    assert restored.threshold_snapshot == report.threshold_snapshot


def test_html_without_diagnosis_is_complete_and_self_contained(tmp_path: Path) -> None:
    report = _report(tmp_path)
    destination = tmp_path / "audit.html"

    html = render_html_report(report)
    write_html_report(report, destination)

    assert destination.read_text(encoding="utf-8") == html
    assert "Dataset overview" in html
    assert "Health Score" in html
    assert "Penalty details" in html
    assert "Issue summary" in html
    assert "Class distribution" in html
    assert "Duplicate groups" in html
    assert "Dataset Doctor diagnosis" in html
    assert "Repair action plan" in html
    assert "Caveats" in html
    assert "Threshold snapshot" in html
    assert report.generated_at.isoformat() in html
    assert "Diagnosis was not requested or is not available." in html
    assert "<img" not in html
    assert "https://" not in html


def test_html_supports_fallback_and_llm_diagnoses(tmp_path: Path) -> None:
    fallback_report = _report(tmp_path, run_doctor=True)

    fallback_html = render_html_report(fallback_report)
    assert fallback_report.diagnosis is not None
    assert fallback_report.diagnosis.generated_by == "deterministic"
    assert "Generated by: deterministic" in fallback_html

    llm_diagnosis = Diagnosis(
        generated_by="llm",
        risk_level="medium",
        summary="Evidence-backed review summary.",
        priority_findings=[
            PriorityFinding(
                rank=1,
                title="Review labels",
                rationale="Observed label evidence requires review.",
                severity=Severity.WARNING,
                issue_ids=[fallback_report.issues[0].issue_id],
                affected_count=1,
                score_penalty=1.0,
            )
        ],
        recommended_actions=[
            RecommendedAction(
                action_id="action-1",
                priority=1,
                title="Inspect evidence",
                description="Confirm the cited issue before changing source data.",
                related_issue_ids=[fallback_report.issues[0].issue_id],
                estimated_effort="low",
            )
        ],
        caveats=["No model-performance improvement is guaranteed."],
    )
    llm_report = fallback_report.model_copy(update={"diagnosis": llm_diagnosis})

    llm_html = render_html_report(llm_report)
    assert "Generated by: llm" in llm_html
    assert "Evidence-backed review summary." in llm_html
    assert "Inspect evidence" in llm_html


def test_html_escapes_all_untrusted_report_text(tmp_path: Path) -> None:
    report = _report(tmp_path)
    attack = "<script>alert('dataset')</script>"
    image_attack = '<img src=x onerror="alert(1)">'
    issue = report.issues[0].model_copy(
        update={
            "relative_path": image_attack,
            "message": attack,
            "suggested_action": image_attack,
            "metrics": {"untrusted": attack},
        }
    )
    manifest = report.manifest.model_copy(
        update={
            "dataset_name": attack,
            "source_archive": image_attack,
            "class_names": {0: image_attack},
        }
    )
    diagnosis = Diagnosis(
        generated_by="llm",
        risk_level="high",
        summary=attack,
        priority_findings=[
            PriorityFinding(
                rank=1,
                title=image_attack,
                rationale=attack,
                inference=image_attack,
                severity=Severity.ERROR,
                issue_ids=[issue.issue_id],
            )
        ],
        recommended_actions=[
            RecommendedAction(
                priority=1,
                title=attack,
                description=image_attack,
                related_issue_ids=[issue.issue_id],
            )
        ],
        caveats=[attack],
    )
    attacked_report = report.model_copy(
        update={
            "manifest": manifest,
            "issues": [issue, *report.issues[1:]],
            "diagnosis": diagnosis,
        }
    )

    html = render_html_report(attacked_report)

    assert attack not in html
    assert image_attack not in html
    assert escape(attack, quote=True) in html
    assert escape(image_attack, quote=True) in html
    assert "<script" not in html.lower()
    assert "<img" not in html.lower()


def test_failed_report_write_does_not_mutate_analysis_result(tmp_path: Path) -> None:
    report = _report(tmp_path)
    before = report.model_dump(mode="json")

    with pytest.raises(OSError):
        write_json_report(report, tmp_path)

    assert report.model_dump(mode="json") == before
